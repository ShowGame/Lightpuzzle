/** 正式手工关卡 */
const ALL_LAYERED_SOURCES: IOpticalLevelLayeredSource[] = [
    ...OPTICAL_LEVEL_LAYERED_SOURCES,
];

export const OPTICAL_LEVELS: IOpticalLevelConfig[] = ALL_LAYERED_SOURCES.map((src) =>
    parseLayeredGridsToLevelConfig(src),
);

const _byId = new Map<number, IOpticalLevelConfig>(OPTICAL_LEVELS.map((lv) => [lv.levelId, lv]));

export function getOpticalLevelById(levelId: number): IOpticalLevelConfig | undefined {
    return _byId.get(levelId);
}

/** 关卡表中最小 levelId（通常为第 1 关） */
export function getFirstOpticalLevelId(): number {
    let first: number | null = null;
    for (const lv of OPTICAL_LEVELS) {
        if (first === null || lv.levelId < first) {
            first = lv.levelId;
        }
    }
    return first ?? 1;
}

/** 大于当前 id 的最小关卡 id；无后续关卡时返回 null */
export function getNextOpticalLevelId(currentLevelId: number): number | null {
    let next: number | null = null;
    for (const lv of OPTICAL_LEVELS) {
        if (lv.levelId <= currentLevelId) {
            continue;
        }
        if (next === null || lv.levelId < next) {
            next = lv.levelId;
        }
    }
    return next;
}
